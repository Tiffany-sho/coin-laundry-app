/**
 * 経費のカテゴリ。
 *
 * ⚠️ **`"use server"` のファイルに置かないこと。** Server Actions のモジュールは
 *    **async 関数しか export できない**ので、定数を export した瞬間にビルドが落ちる
 *    （`Failed to collect page data for …` としか出ず、原因が分かりにくい）。
 *    実際に expenses/action.js に置いてビルドを壊した。
 *
 * ⚠️ **アプリの `src/components/expenses/categories.ts` と同じ綴りにすること。**
 *    2 リポジトリに同じ文字列を持っている（商品 ID と同じ罠）。サーバはこの配列に
 *    含まれるかで弾くので、1 文字でもずれると「カテゴリが不正です」で登録できなくなる。
 */
export const EXPENSE_CATEGORIES = [
  "仕入れ",
  "水道光熱費",
  "家賃",
  "管理費",
  "清掃費",
  "保険料",
  "修繕費",
  "消耗品費",
  "通信費",
  "広告宣伝費",
  "支払手数料",
  "その他",
];

/** 既定のカテゴリ。⚠️ 在庫の仕入れがいちばん多いので先頭に置いてある */
export const DEFAULT_EXPENSE_CATEGORY = EXPENSE_CATEGORIES[0];

/**
 * カテゴリごとの色。ドーナツの扇と、その横の内訳の点に使う。
 *
 * ⚠️ **12 色を色相だけで配らない。** 2026-08-06 まで全部を中間の明るさで
 *    揃えていたため、**家賃(#8B5CF6) と 管理費(#A855F7)**、
 *    **水道光熱費(#F59E0B) と 保険料(#F97316)**、**清掃費(#14B8A6) と
 *    消耗品費(#10B981)** が並ぶと**同じ色にしか見えなかった。**
 *    色相環は 12 等分すると隣どうしが 30 度しか離れず、扇として並べたときに
 *    区別が付かない。
 *
 * **したがって「6 つの色系統 × 濃淡 2 段」で組んである。**
 * 同じ系統の 2 つは必ず**明度で大きく離す**こと。
 *
 * ⚠️ **鮮やかさは `STORE_COLORS`（収益ページの店舗）に合わせてある**（2026-08-06）。
 *    あちらは Tailwind の 300 番台のパステルで、10 色を色相だけで配れている。
 *    ⚠️ **12 色を同じ明度で配り直さないこと。** 10 色なら色相が 36 度おきで足りるが、
 *       12 色だと 30 度しか離れず、**また同じ色に見える。**
 *
 * | 系統 | 濃 | 淡 |
 * |---|---|---|
 * | シアン | 仕入れ | 通信費 |
 * | 黄 | 保険料 | 水道光熱費 |
 * | 紫 | 家賃 | 広告宣伝費 |
 * | 赤桃 | 修繕費 | 管理費 |
 * | 緑 | 清掃費 | 消耗品費 |
 * | グレー | 支払手数料 | その他 |
 *
 * ⚠️ **カテゴリを足すときは系統を 1 つ増やすか、空いている濃淡へ入れること。**
 *    既存の色の近くに足すと、また見分けが付かなくなる。
 * ⚠️ **アプリの `src/components/expenses/categories.ts` と同じ値にすること。**
 *    片方だけ直すと、同じ経費が Web とアプリで違う色になる。
 */
const CATEGORY_COLOR = {
  仕入れ: "#06B6D4",
  水道光熱費: "#FCD34D",
  家賃: "#8B5CF6",
  管理費: "#F9A8D4",
  清掃費: "#22C55E",
  保険料: "#D97706",
  修繕費: "#EF4444",
  消耗品費: "#86EFAC",
  通信費: "#67E8F9",
  広告宣伝費: "#C4B5FD",
  支払手数料: "#64748B",
  その他: "#CBD5E1",
};

/**
 * ⚠️ 未知のカテゴリ（あとから増やした・古いデータ）も来うるので必ず既定色に落とす。
 *    Object.prototype 由来のキーを拾わないよう hasOwnProperty で確かめる。
 */
export function categoryColor(category) {
  return Object.prototype.hasOwnProperty.call(CATEGORY_COLOR, category)
    ? CATEGORY_COLOR[category]
    : CATEGORY_COLOR["その他"];
}
