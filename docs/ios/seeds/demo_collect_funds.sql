--
-- ⚠️ **2025 は 1〜12 月が全部揃っている**（季節性を通しで見せるため）。
--    ⚠️ 2026-07 まで続けてあるのは、**アプリの既定表示が「直近12か月」**で
--       2025 年だけだと 4 か月しか出ないから。**前年同月比**
--       （/funds/summary/monthly は過去 2 年固定）にも両側のデータが要る。
--    ⚠️ **未来の日付は 1 件も入れていない。** 入れるとホームの
--       「過去1ヶ月の集金記録」と集金リマインダーの判定が狂う。
--
-- ⚠️ **金額はすべて 100 円単位。** fundsArray[].funds は**枚数**なので、
--    100 で割り切れないと現金ぶんを機器へ配れない（docs/contracts.md の「単位」）。
-- =====================================================================

