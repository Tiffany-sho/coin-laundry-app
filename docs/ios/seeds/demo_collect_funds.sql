--   季節係数  1月 1.18 / 2月 1.05 / 3月 0.84 / 4月 0.90 / 5月 0.96 / 6月 1.07
--             7月 1.20 / 8月 1.09 / 9月 0.82 / 10月 0.91 / 11月 1.00 / 12月 1.10
--             （3月・9月が谷、1月・7月が山。梅雨の6月と年末の12月も上げてある）
--   前年比    2026 年は 5% 増
