■ 経費を記録する
「経費」から支出を登録できます。金額・カテゴリ・日付を入れるだけです。
記録先は店舗ごとでも、どの店舗にも紐づかない組織全体の支出としてでもかまいません。税理士費用のように店舗で分けられないものは組織全体として残せます。

■ 毎月の固定費は登録しておけば自動で計上される
家賃や水道光熱費のように毎月かかるものは「毎月の固定費」に登録しておくと、毎月の経費に自動で計上されます。毎月入力し直す必要はありません。
金額が変わったときは、その固定費を「今月で終わらせる」を押してから新しく登録してください。金額を書き換えると、計上済みの月にもさかのぼって反映されます。

■ 月ごとの利益を見る
収益ページに「月別利益」が増えました。売上から経費を引いた金額を月ごとに並べます。経費が売上を上回った月は、棒が 0 の線より下へ伸びます。
経費の内訳はカテゴリごとに見られるので、どこにお金がかかっているかを月単位で追えます。

■ 書き出しに含められる
データの書き出しで「経費と月別利益」を選ぶと、集金データと合わせて出せます。確定申告の準備にお使いください。

